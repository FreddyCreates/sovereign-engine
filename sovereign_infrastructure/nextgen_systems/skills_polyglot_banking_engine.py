# 7. C++ FIX PROTOCOL HFT ENGINE
# ============================================================================
class CppFixProtocolEngine:
    """
    Parses and serializes FIX 4.2 / 4.4 tag-value messages ($35=\text{NewOrderSingle}$, $35=\text{ExecutionReport}$)
    and simulates ultra-low latency C++ Limit Order Book (LOB) matching.
    """

    def parse_fix_message(
        self,
        fix_str: str
    ) -> Dict[str, Any]:
        r"""
        Parses FIX tag-value format: `8=FIX.4.2\x0135=D\x0155=AAPL\x0138=100\x0144=185.50\x0154=1\x01`
        """
        delimiter = "\x01" if "\x01" in fix_str else "|"
        tags = {}
        for pair in fix_str.split(delimiter):
            if "=" in pair:
                k, v = pair.split("=", 1)
                tags[k.strip()] = v.strip()

        msg_type_map = {"D": "NewOrderSingle", "8": "ExecutionReport", "3": "Reject", "0": "Heartbeat"}
        msg_type = msg_type_map.get(tags.get("35", ""), "Unknown")

        return {
            "status": "FIX_PARSED",
            "fix_version": tags.get("8", "FIX.4.2"),
            "msg_type": msg_type,
            "symbol": tags.get("55", "N/A"),
            "quantity": int(tags.get("38", 0)),
            "price": float(tags.get("44", 0.0)),
            "side": "BUY" if tags.get("54") == "1" else "SELL" if tags.get("54") == "2" else "UNKNOWN",
            "parsed_tags": tags
        }


